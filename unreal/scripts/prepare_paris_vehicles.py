"""Convert the pinned CC0 sedan into centimetre meshes with separate wheel pivots.

The archived OBJ uses negative indices relative to each current attribute list.
Source geometry is preserved except zero-area faces and scale/axis conversion.
No geographic data or driving route is regenerated by this script.
"""
from collections import defaultdict
import hashlib
import json
from pathlib import Path
import struct
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / 'unreal/assets/paris-vehicles'
RECIPE = 'paris_sedan_pbr_v1'


def read_obj(path):
    positions, normals, texcoords = [], [], []
    groups = defaultdict(list)
    group, material = '', ''
    def index(value, size):
        i = int(value)
        return i - 1 if i > 0 else size + i
    with path.open(encoding='utf-8') as source:
        for line in source:
            fields = line.split()
            if not fields: continue
            tag, values = fields[0], fields[1:]
            if tag == 'v': positions.append([float(v) for v in values[:3]])
            elif tag == 'vn': normals.append([float(v) for v in values[:3]])
            elif tag == 'vt': texcoords.append([float(v) for v in values[:2]])
            elif tag == 'o': group = ' '.join(values)
            elif tag == 'usemtl': material = ' '.join(values)
            elif tag == 'f':
                polygon = []
                for text in values:
                    v = text.split('/')
                    polygon.append((index(v[0], len(positions)), index(v[1], len(texcoords)) if len(v)>1 and v[1] else -1, index(v[2], len(normals)) if len(v)>2 and v[2] else -1))
                for i in range(1,len(polygon)-1): groups[group,material].extend((polygon[0],polygon[i],polygon[i+1]))
    return np.asarray(positions), np.asarray(normals), np.asarray(texcoords), groups


def split_conflicting_edges(positions,normal,uv,triangles):
    """Preserve overlapping authored surfaces without nonmanifold UE edges."""
    edges={};directed=set();extra=[];fixed=[]
    for row in triangles:
        t=[int(v) for v in row];pairs=[(t[0],t[1]),(t[1],t[2]),(t[2],t[0])]
        if any((a,b) in directed or edges.get(tuple(sorted((a,b))),0)>=2 for a,b in pairs):
            t=[len(positions)+len(extra)+i for i in range(3)];extra.extend(int(v) for v in row);pairs=[(t[0],t[1]),(t[1],t[2]),(t[2],t[0])]
        for a,b in pairs:
            directed.add((a,b));edge=tuple(sorted((a,b)));edges[edge]=edges.get(edge,0)+1
        fixed.append(t)
    if extra:
        positions=np.concatenate((positions,positions[extra]));normal=np.concatenate((normal,normal[extra]));uv=np.concatenate((uv,uv[extra]))
    return positions,normal,uv,np.asarray(fixed,dtype='<u4'),len(extra)//3


def project_surface_uv(p,n,t):
    """UVs for texture-free PBR: choose a nondegenerate plane per triangle.

    The archive lacks UVs for most surfaces. Splitting at projection seams
    preserves the authored smooth normals while producing valid UE tangents.
    """
    lookup={};vertices=[];tex=[];faces=[]
    cross=np.cross(p[t[:,1]]-p[t[:,0]],p[t[:,2]]-p[t[:,0]])
    for triangle,plane in zip(t,np.abs(cross).argmax(axis=1)):
        face=[];axes=((1,2),(0,2),(0,1))[plane]
        for vertex in triangle:
            key=(int(vertex),int(plane))
            if key not in lookup:
                lookup[key]=len(vertices);vertices.append(int(vertex));tex.append(p[vertex,list(axes)]/100.)
            face.append(lookup[key])
        faces.append(face)
    return p[vertices],n[vertices],np.asarray(tex,dtype='<f4'),np.asarray(faces,dtype='<u4')


def prepare():
    manifest = json.loads((ASSETS/'manifest.json').read_text(encoding='utf-8'))
    obj = ASSETS/'Raw/bmw.obj'
    if hashlib.sha256(obj.read_bytes()).hexdigest()!=manifest['files']['bmw.obj']['sha256']:
        raise ValueError('Vehicle source mesh differs from pinned CC0 archive')
    p,n,uv,groups=read_obj(obj)
    scale=420./np.ptp(p[:,0]);origin=np.array([(p[:,0].max()+p[:,0].min())/2,p[:,1].min(),(p[:,2].max()+p[:,2].min())/2])
    # Source -X is the nose, Y is up. UE +X is forward, +Y is right, +Z up.
    basis=np.array([[-1.,0,0],[0,0,1.],[0,1.,0]])
    points=((p-origin)@basis.T*scale).astype('<f4')
    normals=(n@basis.T).astype('<f4');normals/=np.maximum(np.linalg.norm(normals,axis=1,keepdims=True),1.e-20)
    wheel_centres={};wheel_radius=0
    for (name,mat),faces in groups.items():
        if mat!='TireRubber':continue
        verts=points[np.array(faces)[:,0]];lo,hi=verts.min(0),verts.max(0);pivot=(lo+hi)/2
        key=('front' if pivot[0]>0 else 'rear')+('_right' if pivot[1]>0 else '_left')
        wheel_centres[key]=pivot;wheel_radius=float((hi[2]-lo[2])/2)
    if len(wheel_centres)!=4:raise ValueError('Expected four distinct physical wheel centres')
    material_roles=dict(CarShellNew='paint',Plate='plate',MatteBlack='plastic',BMWSilver='alloy',BMWWhite='white',BMWBlack='black',BMWBlue='blue',Tailight='brake',Chrome='chrome',Glass='glass',BlackPlastic='plastic',HeadlightMatte='lamp_reflector',Interior='interior',HeadlightGlass='glass',HeadlightChrome='chrome',HeadLightAngelEye='daylight',HeadLightGlass='daylight',ChromeMatte='alloy',Mirror='mirror',Material='caliper',TireRubber='rubber',Brake='disc',interiorRoof='interior')
    parts=defaultdict(lambda:defaultdict(list))
    plate_vertices=[]
    for (name,mat),faces in groups.items():
        if mat not in material_roles:raise ValueError('Unmapped archived material '+mat)
        role=material_roles[mat]
        part='windows' if role=='glass' else 'body'
        if name.startswith(('Tire','Brake4')):
            centre=points[np.array(faces)[:,0]].mean(0)
            part='wheel_'+min(wheel_centres,key=lambda k:np.linalg.norm(wheel_centres[k]-centre))
        parts[part][role].extend(faces)
        if role=='plate':plate_vertices.extend(np.array(faces)[:,0])
    plate_p=points[plate_vertices];plate_width=float(np.ptp(plate_p[:,1]));plate_zmin=float(plate_p[:,2].min());plate_height=float(np.ptp(plate_p[:,2]))
    generated=ASSETS/'Generated';generated.mkdir(exist_ok=True)
    output=[];total=0;removed=0
    for part,materials in sorted(parts.items()):
        pivot=wheel_centres[part[6:]] if part.startswith('wheel_') else np.zeros(3)
        item=dict(id=part,pivot_cm=pivot.tolist(),primitives=[])
        for role,faces in sorted(materials.items()):
            keys=list(dict.fromkeys(faces));lookup={k:i for i,k in enumerate(keys)};a=np.array(keys,dtype=np.int64)
            positions=(points[a[:,0]]-pivot).astype('<f4');normal=normals[a[:,2]].copy()
            if (a[:,2]<0).any():raise ValueError('Missing archived normal')
            tex=(positions[:,[0,2]]/100).astype('<f4');has_uv=a[:,1]>=0;tex[has_uv]=uv[a[has_uv,1]]
            if role=='plate':
                tex[:,0]=points[a[:,0],1]/max(plate_width,1.)+.5
                tex[:,1]=1.-(points[a[:,0],2]-plate_zmin)/max(plate_height,1.)
                tex[:,0]=np.where(points[a[:,0],0]>0,1.-tex[:,0],tex[:,0])
            triangles=np.array([lookup[k] for k in faces],dtype='<u4').reshape(-1,3)
            cross=np.cross(positions[triangles[:,1]]-positions[triangles[:,0]],positions[triangles[:,2]]-positions[triangles[:,0]])
            valid=np.linalg.norm(cross,axis=1)>1.e-7;removed+=int((~valid).sum());triangles=triangles[valid];cross=cross[valid]
            used,remapped=np.unique(triangles,return_inverse=True)
            positions,normal,tex=positions[used],normal[used],tex[used];triangles=remapped.reshape(-1,3).astype('<u4')
            missing=np.linalg.norm(normal,axis=1)<.5
            if missing.any():
                recovered=np.zeros_like(normal)
                for column in range(3):np.add.at(recovered,triangles[:,column],cross)
                normal[missing]=recovered[missing]
                normal/=np.maximum(np.linalg.norm(normal,axis=1,keepdims=True),1.e-20)
            if (np.linalg.norm(normal,axis=1)<.5).any():raise ValueError('Unrecoverable vehicle source normal')
            reverse=np.einsum('ij,ij->i',cross,normal[triangles].sum(axis=1))>0
            triangles[reverse]=triangles[reverse][:,[0,2,1]] # Clockwise UE front faces.
            if role!='plate':positions,normal,tex,triangles=project_surface_uv(positions,normal,triangles)
            positions,normal,tex,triangles,split=split_conflicting_edges(positions,normal,tex,triangles)
            blob=struct.pack('<8sII',b'NDSCAN01',len(positions),len(triangles))+positions.tobytes()+normal.tobytes()+tex.tobytes()+triangles.tobytes()
            digest=hashlib.sha256(blob).hexdigest();filename=part+'_'+role+'.bin';(generated/filename).write_bytes(blob)
            item['primitives'].append(dict(role=role,file=filename,sha256=digest,vertices=len(positions),triangles=len(triangles),inferred_planar_uv_vertices=len(positions) if role!='plate' else 0,split_nonmanifold_faces=split))
            total+=len(triangles)
        geometry_hash=hashlib.sha256(json.dumps(item,sort_keys=True).encode()).hexdigest()
        item['asset']='/Game/ParisPhotoreal/Vehicles/SM_ParisSedan_'+part+'_'+geometry_hash[:12]
        output.append(item)
    dimensions=np.ptp(points,axis=0).tolist();radius=float(np.linalg.norm(points[:,:2],axis=1).max())
    if radius>240. or points[:,2].min()<-.01:raise ValueError('Detailed car exceeds existing swept clearance / floor')
    result=dict(recipe=RECIPE,source_url=manifest['source_url'],license=manifest['license'],authors=manifest['authors'],source_geometry_sha256=manifest['files']['bmw.obj']['sha256'],parts=output,dimensions_cm=dimensions,swept_radius_cm=radius,wheel_radius_cm=wheel_radius,wheelbase_cm=float(max(v[0] for v in wheel_centres.values())-min(v[0] for v in wheel_centres.values())),source_triangles=total,removed_zero_area_faces=removed,provenance='CC0 archived sedan geometry; uniform 4.2m traffic envelope; authored PBR conversion and fictional plate; simulated vehicles, not observed traffic')
    (generated/'source.json').write_text(json.dumps(result,indent=2,allow_nan=False)+'\n',encoding='utf-8')
    print(json.dumps({k:v for k,v in result.items() if k!='parts'},indent=2))
    print('PARIS_VEHICLE_GEOMETRY_READY')
    return result


if __name__=='__main__':
    prepare()
